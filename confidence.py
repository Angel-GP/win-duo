"""识别置信度 —— 把三个门控阈值收成**一个 0~100 的档位**。

═══════════════════════════════════════════════════════════════════════
为什么要收成一个
═══════════════════════════════════════════════════════════════════════

摄像头测角要防的是"场景一变玻璃层就自己动"。判据本来有三条 (内点数 /
内点率 / 残差), 但它们是**同一套匹配流程里逐层筛出来的三个量**, 一起松一起紧:

    匹配 ──RANSAC──> 内点 ──最小二乘──> 残差

让用户同时调三个数字, 等于把一件"整体松紧"的事拆成三件 —— 调了一个不知道
另外两个要不要跟着动。收成一个档位更贴近实际心智。

═══════════════════════════════════════════════════════════════════════
映射 (线性, 单调)
═══════════════════════════════════════════════════════════════════════

    档位        内点率下限      残差上限      含义
    ─────────────────────────────────────────────────────────
      0         关闭           关闭         退回旧行为 (只看内点绝对数)
      1         1%            1.98°        极松
     50         50%           1.00°        **默认** (见下面的实测依据)
    100         95%           0.05°        极严

    内点率 = min(0.95, 档位/100)
    残差   = max(0.05, 2.0 × (1 - 档位/100))

**档位 0 特判成"关闭"**, 不走公式: 公式在 0 处会给出残差 2.0° (一个很松但
仍然存在的门), 而"0 = 不检查"是本项目其它旋钮一致的约定 (见 render_fps 等)。

**两端都刻意不取极端值**: 100 档给的是 95% / 0.05° 而不是 100% / 0° ——
后者永远不可能通过, 等于把追踪彻底卡死; 前者仍然可达 (实测好场景内点率
最低 0.955、残差最小 0.0012), 只是余量很小。

═══════════════════════════════════════════════════════════════════════
50 档 = 默认值的实测依据
═══════════════════════════════════════════════════════════════════════

本机真实摄像头实测 362 帧静止场景:

    内点率   最小 0.955   中位 0.997   最大 1.000
    残差     最小 0.0012  中位 0.013   最大 0.416 度

50 档给出 50% / 1.00°, 对上面这组实测值都留了约 **2 倍余量** —— 正常场景
绝不会被误杀 (用这套默认值实跑 452 帧, 丢弃 0 帧)。

取这个松紧度而不是更松, 是因为一个**不对称性**: **丢帧是良性的** —— 参考帧
会立刻换成当前帧, 下一帧就在新画面上重新锚定, 不会一路错下去; 而**误采信
才是要防的 bug** (场景一变, 玻璃层自己动)。所以宁可偏紧。

═══════════════════════════════════════════════════════════════════════
为什么单独一个模块
═══════════════════════════════════════════════════════════════════════

映射要被两边用: `angles/camera.py` (真去门控) 和设置窗口 (显示"这一档等于
什么")。而 `angles/camera.py` **顶层就 import cv2**, opencv 的 DLL 有 ~116MB
—— 界面为了算一个百分比去 import 它是不行的 (见 angles/hub.py 的懒导入说明)。
放这里两边都能安全 import。
"""

#: 默认档位
DEFAULT = 50
#: 档位范围
MIN_LEVEL, MAX_LEVEL = 0, 100

#: 满档 (100) 时的内点率下限
_RATIO_AT_FULL = 0.95
#: 档位趋近 0+ 时的残差上限 (度)
_RESID_AT_NEAR_ZERO = 2.0
#: 满档 (100) 时的残差上限 (度)
_RESID_AT_FULL = 0.05


def as_level(value, default=DEFAULT):
    """把配置里的值夹到 [0, 100] 的整数档位; 坏值退回 default。

    **坏值退回 default 而不是 0** —— 0 的含义是"关掉门控", 一个笔误
    (比如配置里写成 "abc") 不该把保护悄悄撤掉 (和 logkeep.as_int 同一个道理)。
    """
    try:
        v = int(round(float(value)))
    except (TypeError, ValueError):
        return int(default)
    return max(MIN_LEVEL, min(MAX_LEVEL, v))


def to_gates(level):
    """档位 -> `(内点率下限, 残差上限(度))`。

    两者都为 0 表示**该项不检查** (档位 0 = 整体关闭)。
    """
    c = as_level(level)
    if c <= 0:
        return 0.0, 0.0
    ratio = min(_RATIO_AT_FULL, c / 100.0)
    resid = max(_RESID_AT_FULL, _RESID_AT_NEAR_ZERO * (1.0 - c / 100.0))
    return ratio, resid


def describe(level):
    """给设置界面用的一句话: 这一档实际等于什么。"""
    c = as_level(level)
    if c <= 0:
        return "关闭 —— 退回旧行为（只看内点绝对数）"
    ratio, resid = to_gates(c)
    return "内点率 >= %.0f%%，残差 <= %.2f°" % (ratio * 100.0, resid)
